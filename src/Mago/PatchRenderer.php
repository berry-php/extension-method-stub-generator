<?php

declare(strict_types=1);

namespace Berry\ExtensionMethodStubGenerator\Mago;

use Berry\ExtensionMethodStubGenerator\Dto\Argument;
use Berry\ExtensionMethodStubGenerator\Dto\ClassStub;
use Berry\ExtensionMethodStubGenerator\Dto\Method;
use Berry\ExtensionMethodStubGenerator\StubRenderer;
use LogicException;

final class PatchRenderer
{
    public function render(ClassStub $target, string $declaration): string
    {
        $patch = new ClassStub($target->namespace, $target->className);
        $scopes = [];
        $imports = [];

        foreach ($target->methods as $key => $method) {
            $scope = [];

            foreach ($target->methodImports[$key] ?? array_values($target->uses) as $import) {
                $parts = preg_split('/\s+as\s+/i', trim($import, '\\ '));

                if ($parts === false) {
                    throw new LogicException("Could not parse import '{$import}'");
                }

                $name = $parts[0] ?? '';
                if ($name === '') {
                    continue;
                }

                $segments = explode('\\', $name);
                $alias = $parts[1] ?? array_pop($segments);
                $aliasKey = strtolower($alias);

                if (isset($scope[$aliasKey]) && strcasecmp($scope[$aliasKey], $name) !== 0) {
                    throw new LogicException(
                        "Ambiguous import '{$alias}' for '{$target->namespace}\\{$target->className}::{$method->name}'; use explicit aliases in the extension definition",
                    );
                }

                $scope[$aliasKey] = $name;
                $imports[$aliasKey][strtolower($name)] = ['name' => $name, 'alias' => $alias];
            }

            $scopes[$key] = $scope;
        }

        foreach ($imports as $key => $names) {
            if (count($names) !== 1 || $key === strtolower($target->className)) {
                continue;
            }

            $import = reset($names);
            $segments = explode('\\', $import['name']);
            $short = array_pop($segments);
            $patch->uses[$key] = $import['name'] . ($short !== $import['alias'] ? ' as ' . $import['alias'] : '');
        }

        foreach ($target->methods as $key => $method) {
            $mapType = fn(?string $type): ?string => $this->qualify($type, $scopes[$key], $patch->uses);
            $args = [];

            foreach ($method->args as $arg) {
                $type = trim($arg->type ?? '');
                $variadic = str_starts_with($arg->name, '...') || str_ends_with($type, '...');

                if (str_ends_with($type, '...')) {
                    $type = rtrim(substr($type, 0, -3));
                }

                $args[] = new Argument(
                    name: ($variadic ? '...' : '') . ltrim($arg->name, '.$'),
                    type: $mapType($type !== '' ? $type : null),
                    defaultValue: $mapType($arg->defaultValue),
                );
            }

            $patch->methods[$key] = new Method(
                name: $method->name,
                doc: $method->doc !== null ? str_replace(["\r", "\n", '*/'], [' ', ' ', '* /'], $method->doc) : null,
                returns: $mapType($method->returns),
                args: $args,
            );
        }

        $namespace = $patch->namespace !== '' ? "namespace {$patch->namespace};\n\n" : '';
        $uses = $patch->uses;

        sort($uses, SORT_STRING);

        $importsString = count($uses) > 0 ? 'use ' . implode(";\nuse ", $uses) . ";\n\n" : '';
        $doc = (new StubRenderer())->renderDocBlock($patch);

        return (
            "<?php\n\ndeclare(strict_types=1);\n\n"
                . "// Generated by berry/extension-method-stub-generator.\n// Do not edit; regenerate through Composer.\n\n"
                . $namespace
                . $importsString
                . ($doc !== '' ? $doc . "\n" : '')
                . "{$declaration} {$patch->className}\n{\n}\n"
        );
    }

    /**
     * @param array<string, string> $scope
     * @param array<string, string> $imports
     */
    private function qualify(?string $type, array $scope, array $imports): ?string
    {
        if ($type === null) {
            return null;
        }

        return preg_replace_callback(
            '/\x27(?:\\\\.|[^\x27])*\x27|"(?:\\\\.|[^"])*"|(?<![a-zA-Z0-9_$\\\\])[a-zA-Z_][a-zA-Z0-9_\\\\]*(?![a-zA-Z0-9_]|\s*:(?!:))/',
            static function (array $match) use ($scope, $imports): string {
                $parts = explode('\\', $match[0], 2);
                $key = strtolower($parts[0]);
                if (!isset($scope[$key])) {
                    return $match[0];
                }

                $prefix = isset($imports[$key]) ? explode(' as ', $imports[$key])[1] ?? $parts[0] : '\\' . $scope[$key];

                return $prefix . (isset($parts[1]) ? '\\' . $parts[1] : '');
            },
            $type,
        ) ?? $type;
    }
}
