<?php

declare(strict_types=1);

namespace Berry\ExtensionMethodStubGenerator;

use Berry\ExtensionMethodStubGenerator\Dto\Argument;
use Berry\ExtensionMethodStubGenerator\Dto\ClassStub;
use Berry\ExtensionMethodStubGenerator\Dto\Method;

final class StubRenderer
{
    public function render(ClassStub $class): string
    {
        $namespaceDeclaration = $class->namespace !== '' ? "namespace {$class->namespace};" : '';

        $uses = $class->uses;
        sort($uses, SORT_STRING);

        $usesString = count($uses) > 0 ? "\nuse " . implode(";\nuse ", $uses) . ";\n" : '';

        $docBlock = $this->renderDocBlock($class);

        return trim(<<<PHP
            <?php declare(strict_types=1);

            // This file was automatically generated by berry/extension-method-stub-generator, please don't edit it
            {$namespaceDeclaration}
            {$usesString}
            {$docBlock}
            class {$class->className}
            {
                // stub
            }
            PHP);
    }

    public function renderDocBlock(ClassStub $class): string
    {
        $methods = $class->methods;
        usort($methods, static fn(Method $a, Method $b) => strcmp($a->name, $b->name));

        $docString = '';

        foreach ($methods as $method) {
            $args = array_map($this->renderArgument(...), $method->args);
            $returns = $method->returns !== null ? $method->returns . ' ' : '';
            $docString .=
                "\n * @method {$returns}{$method->name}(" . implode(', ', $args) . ') ' . ($method->doc ?? '');
        }

        return $docString !== '' ? "/**{$docString}\n */" : '';
    }

    private function renderArgument(Argument $argument): string
    {
        $type = $argument->type !== null ? $argument->type . ' ' : '';
        $default = $argument->defaultValue !== null ? ' = ' . $argument->defaultValue : '';
        $variadic = str_starts_with($argument->name, '...') ? '...' : '';
        $name = $variadic !== '' ? substr($argument->name, 3) : $argument->name;

        return "{$type}{$variadic}\${$name}{$default}";
    }
}
